"""A case's evidence report: one summary, also rendered as a PDF and an Excel workbook built from it."""

from datetime import datetime
from io import BytesIO
from xml.sax.saxutils import escape

from django.utils import timezone
from openpyxl import Workbook
from openpyxl.styles import Font
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from fraud.services.investigation import InvestigationService

FLAGGED_LABELS = {
    "transaction_id": "Transaction", "employee_id": "Employee ID", "employee_name": "Employee", "department": "Department",
    "account_number": "Account", "pay_period": "Pay period", "payment_date": "Date", "amount": "Amount",
    "net_salary": "Net salary", "invoice_number": "Invoice", "approver": "Approver", "approver_id": "Approver ID",
    "outside_by": "Outside by",
}


def _when(value) -> str:
    """An ISO timestamp from the summary as `2026-10-15 09:00 UTC`; dates and blanks pass through."""
    if not value or "T" not in str(value):
        return value or "-"
    return datetime.fromisoformat(str(value)).strftime("%Y-%m-%d %H:%M %Z").strip()


def _name(person) -> str:
    return person["full_name"] if person else "-"


def _flagged_columns(alerts) -> list[str]:
    columns = []
    for alert in alerts:
        for record in alert["flagged_records"]:
            columns += [key for key in record if key not in columns]
    return columns


def _case_facts(data) -> list[tuple[str, str]]:
    case = data["case"]
    return [
        ("Case", f"{case['reference']}: {case['title']}"),
        ("Status", case["status"]),
        ("Priority", case["priority"]),
        ("Investigator", _name(case["investigator"])),
        ("Reviewer", _name(case["reviewer"])),
        ("Opened", _when(case["created_at"])),
        ("Closed", _when(case["closed_at"])),
        ("Description", case["description"] or "-"),
        ("Generated by", _name(data["generated_by"])),
        ("Generated at", _when(data["generated_at"])),
    ]


def _analysis_rows(data) -> list[tuple[str, str]]:
    analysis = data["analysis"]
    currency = analysis["currency"]
    return [
        ("Total exposure", f"{analysis['total_exposure']} {currency}"),
        ("Duplicate amount", f"{analysis['duplicate_amount']} {currency}"),
        ("Risk score", str(analysis["risk_score"])),
        ("Flagged transactions", str(analysis["transaction_count"])),
    ]


class ReportService:
    @staticmethod
    def gather(case, user) -> dict:
        """Everything the report holds, as model objects and dicts for `ReportSerializer`."""
        alerts = list(case.alerts.select_related("assigned_reviewer").order_by("number"))
        investigation = InvestigationService.build(case.organisation, alerts, {"type": "case", "reference": case.reference})
        return {
            "case": case,
            "alerts": alerts,
            "analysis": investigation["analysis"],
            "related": investigation["related"],
            "evidence": list(case.evidence.select_related("file", "added_by").order_by("created_at")),
            "comments": list(case.comments.select_related("author").order_by("created_at")),
            "history": list(case.events.select_related("actor").order_by("created_at")),
            "generated_at": timezone.now(),
            "generated_by": user,
        }

    @staticmethod
    def file_name(data, extension) -> str:
        return f"{data['case']['reference']}-evidence-report.{extension}"

    @staticmethod
    def pdf(data) -> bytes:
        styles = getSampleStyleSheet()
        small = styles["BodyText"].clone("small", fontSize=8, leading=10)

        def text(value, style=styles["BodyText"]):
            # Paragraph reads markup, so user text is escaped first.
            return Paragraph(escape(str(value)), style)

        def table(rows, header=True):
            cells = [[text(cell, small) for cell in row] for row in rows]
            grid = Table(cells, repeatRows=1 if header else 0, hAlign="LEFT")
            style = [("GRID", (0, 0), (-1, -1), 0.25, colors.grey), ("VALIGN", (0, 0), (-1, -1), "TOP")]
            if header:
                style.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8ECF2")))
            grid.setStyle(TableStyle(style))
            return grid

        def section(title, rows, empty="None."):
            story.append(text(title, styles["Heading2"]))
            story.append(table(rows) if len(rows) > 1 else text(empty))

        case = data["case"]
        story = [text(f"{case['reference']} evidence report", styles["Title"]), table(_case_facts(data), header=False)]
        story.append(text("Transaction analysis", styles["Heading2"]))
        story.append(table(_analysis_rows(data), header=False))

        related = data["related"]
        section("Related entities", [("Type", "ID", "Name", "Role", "Department")] + [
            ("Employee", e["id"], e["name"], e["role"], e["department"]) for e in related["employees"]
        ] + [("Vendor", v["id"], v["name"], "", "") for v in related["vendors"]] + [
            ("Approver", a["id"], a["name"], a["role"], a["department"]) for a in related["approvers"]
        ])

        story.append(text("Alerts", styles["Heading2"]))
        for alert in data["alerts"]:
            story.append(text(f"{alert['reference']}: {alert['title']}", styles["Heading3"]))
            story.append(text(
                f"{alert['risk_type']}, severity {alert['severity']}, risk score {alert['risk_score']}, "
                f"status {alert['status']}, detected {_when(alert['detected_at'])}"
            ))
            story.append(text(alert["explanation"]))
            columns = _flagged_columns([alert])
            if columns:
                story.append(Spacer(1, 2 * mm))
                story.append(table([[FLAGGED_LABELS.get(c, c) for c in columns]] + [
                    [record.get(c, "") for c in columns] for record in alert["flagged_records"]
                ]))
        if not data["alerts"]:
            story.append(text("None."))

        section("Evidence", [("File", "Type", "Size (bytes)", "Source", "Added by", "Added at")] + [
            (e["file_name"], e["content_type"], e["size"], e["source"], _name(e["added_by"]), _when(e["added_at"]))
            for e in data["evidence"]
        ])
        section("Comments", [("When", "Author", "Comment")] + [
            (_when(c["created_at"]), _name(c["author"]), c["text"]) for c in data["comments"]
        ])
        section("History", [("When", "Who", "Event", "From", "To", "Detail")] + [
            (_when(h["created_at"]), _name(h["actor"]), h["type"], h["from_status"], h["to_status"], h["detail"])
            for h in data["history"]
        ])

        def footer(canvas, doc):
            canvas.setFont("Helvetica", 8)
            canvas.drawRightString(doc.pagesize[0] - 15 * mm, 8 * mm, f"{case['reference']} - page {doc.page}")

        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer, pagesize=landscape(A4), title=f"{case['reference']} evidence report",
            leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
        )
        doc.build(story, onFirstPage=footer, onLaterPages=footer)
        return buffer.getvalue()

    @staticmethod
    def xlsx(data) -> bytes:
        book = Workbook()
        sheets = {}

        def sheet(title, header):
            ws = book.active if not sheets else book.create_sheet()
            ws.title = title
            ws.append(header)
            for cell in ws[1]:
                cell.font = Font(bold=True)
            ws.freeze_panes = "A2"
            sheets[title] = ws
            return ws

        def add(ws, row):
            ws.append(list(row))
            for cell in ws[ws.max_row]:
                # openpyxl would save text starting with "=" as a formula that Excel runs.
                if isinstance(cell.value, str) and cell.value.startswith("="):
                    cell.data_type = "s"

        summary = sheet("Summary", ["Field", "Value"])
        for row in _case_facts(data) + _analysis_rows(data):
            add(summary, row)

        alerts = sheet("Alerts", ["Reference", "Title", "Risk type", "Severity", "Status", "Risk score", "Confidence", "Entity", "Explanation", "Detected at"])
        for a in data["alerts"]:
            add(alerts, [a["reference"], a["title"], a["risk_type"], a["severity"], a["status"], a["risk_score"], a["confidence"], a["entity_name"], a["explanation"], _when(a["detected_at"])])

        columns = _flagged_columns(data["alerts"])
        flagged = sheet("Flagged records", ["Alert"] + [FLAGGED_LABELS.get(c, c) for c in columns])
        for a in data["alerts"]:
            for record in a["flagged_records"]:
                add(flagged, [a["reference"]] + [record.get(c, "") for c in columns])

        evidence = sheet("Evidence", ["File", "Type", "Size (bytes)", "Source", "Added by", "Added at"])
        for e in data["evidence"]:
            add(evidence, [e["file_name"], e["content_type"], e["size"], e["source"], _name(e["added_by"]), _when(e["added_at"])])

        comments = sheet("Comments", ["When", "Author", "Comment"])
        for c in data["comments"]:
            add(comments, [_when(c["created_at"]), _name(c["author"]), c["text"]])

        history = sheet("History", ["When", "Who", "Event", "From", "To", "Detail"])
        for h in data["history"]:
            add(history, [_when(h["created_at"]), _name(h["actor"]), h["type"], h["from_status"], h["to_status"], h["detail"]])

        for ws in sheets.values():
            for column in ws.columns:
                width = max(len(str(cell.value or "")) for cell in column)
                ws.column_dimensions[column[0].column_letter].width = min(max(width + 2, 10), 60)
        buffer = BytesIO()
        book.save(buffer)
        return buffer.getvalue()
